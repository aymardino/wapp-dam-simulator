// Writes index.html from scenes.json: the root composition that mounts the scenes back to back, each new scene wiping
// in over the last `overlap` seconds of the previous one. Run after changing a scene's duration or the scene list
// (a scene that gets longer simply holds its last state longer).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { overlap, scenes } = JSON.parse(readFileSync(join(root, 'scenes.json'), 'utf8'))
let t = 0
const slots = [], rows = []
scenes.forEach((s, i) => {
  const start = Math.round(t * 100) / 100
  slots.push(`      <div id="el-${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${start}" data-duration="${s.duration}" data-track-index="${i + 1}" data-width="1920" data-height="1080"></div>`)
  rows.push(`       ${s.id.padEnd(12)} ${start.toFixed(2).padStart(6)} s → ${(start + s.duration).toFixed(2).padStart(6)} s  (${s.duration} s)`)
  t = start + s.duration - overlap
})
const total = Math.round((t + overlap) * 100) / 100
const html = `<!doctype html>
<!-- WAPP DAM Simulator, motion design video (HyperFrames). Generated by scripts/build-index.mjs from scenes.json.
     Root composition: mounts the scenes of compositions/ back to back. Each scene but the first wipes in over the
     last ${overlap} s of the previous one (WAPP.wipeIn). Scenes, start → end:
${rows.join('\n')}
     Language: the "lang" variable (fr by default; render with --variables '{"lang":"en"}'). Text: assets/strings.js. -->
<html lang="fr" data-composition-variables='[{"id":"lang","type":"enum","label":"Langue / Language","default":"fr","options":[{"value":"fr","label":"Français"},{"value":"en","label":"English"}]}]'>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>WAPP DAM Simulator · video</title>
    <link rel="stylesheet" href="assets/theme.css" />
    <script src="node_modules/gsap/dist/gsap.min.js"></script>
    <script src="node_modules/gsap/dist/SplitText.min.js"></script>
    <script src="node_modules/gsap/dist/DrawSVGPlugin.min.js"></script>
    <script src="node_modules/gsap/dist/MotionPathPlugin.min.js"></script>
    <script src="node_modules/gsap/dist/CustomEase.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #07241C; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; background: #07241C; font-family: "Roboto", sans-serif; color: #FFFFFF; }
      [data-composition-id="main"] > div[data-composition-src] { position: absolute; inset: 0; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
${slots.join('\n')}
    </div>
    <!-- after the root element: the "lang" variable is only readable from here (WAPP.lang), and before the scenes -->
    <script src="assets/strings.js"></script>
    <script src="assets/data.js"></script>
    <script src="assets/wapp.js"></script>
    <script>
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`
writeFileSync(join(root, 'index.html'), html)
console.log(`index.html: ${scenes.length} scenes, ${total} s`)
